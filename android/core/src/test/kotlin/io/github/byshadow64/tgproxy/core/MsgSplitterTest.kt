package io.github.byshadow64.tgproxy.core

import org.junit.Assert.*
import org.junit.Test
import java.security.MessageDigest

class MsgSplitterTest {
    private fun oracle(protocol: TransportProtocol, plain: ByteArray, chunks: List<Int>, expected: List<List<Int>>, sha: String) {
        val budget = SplitterBudget(4L * 1024 * 1024)
        val cipher = ByteArray(plain.size) { (plain[it].toInt() xor 0xa5).toByte() }
        MsgSplitter(protocol, budget).use { splitter ->
            val emitted = java.io.ByteArrayOutputStream()
            var offset = 0
            chunks.forEachIndexed { index, count ->
                val parts = splitter.split(cipher.copyOfRange(offset, offset + count), plain.copyOfRange(offset, offset + count))
                assertEquals(expected[index], parts.map { it.size })
                parts.forEach(emitted::write); offset += count
            }
            assertEquals(plain.size, offset)
            assertArrayEquals(cipher, emitted.toByteArray())
            assertEquals(sha, MessageDigest.getInstance("SHA-256").digest(emitted.toByteArray()).joinToString("") { "%02x".format(it.toInt() and 255) })
            assertEquals(0L, budget.used)
            assertFalse(splitter.disabled)
        }
    }

