    @Test fun retainsOneMiBMediaPlusAllPaddedTransportBytesAsOnePacket() {
        val size = 1024 * 1024
        val plain = byteArrayOf(15, 0, 16, 0) + ByteArray(size) { 'm'.code.toByte() } + ByteArray(15) { 'p'.code.toByte() }
        val chunks = listOf(1, 2) + List(16) { 65536 } + listOf(16)
        oracle(TransportProtocol.PADDED_INTERMEDIATE, plain, chunks, List(chunks.size - 1) { emptyList<Int>() } + listOf(listOf(size + 19)),
            "f4cb4fbb0d2d9e5a0bce36be03aa6862faa1a3569f0e900d743afe48c6467904")
    }

    @Test fun giantDeclaredLengthsFallBackToBoundedStreamingForEveryProtocol() {
        for (protocol in TransportProtocol.entries) {
            val budget = SplitterBudget(128 * 1024)
            MsgSplitter(protocol, budget).use { splitter ->
                val header = ByteArray(4) { -1 }
                val plain = header + ByteArray(2 * 65536) { 'x'.code.toByte() }
                val cipher = ByteArray(plain.size) { (plain[it].toInt() xor 0xa5).toByte() }
                val chunks = listOf(1, 2, 1, 65536, 65536)
                val expected = listOf(emptyList(), emptyList(), listOf(1, 2, 1), listOf(65536), listOf(65536))
                val output = java.io.ByteArrayOutputStream(); var offset = 0
                chunks.forEachIndexed { index, count ->
                    val parts = splitter.split(cipher.copyOfRange(offset, offset + count), plain.copyOfRange(offset, offset + count))
                    // The segmented implementation may emit the four-byte invalid prefix as three small pieces.
                    assertEquals(expected[index].sum(), parts.sumOf { it.size })
                    assertTrue(parts.all { it.size <= STREAM_CHUNK_BYTES }); parts.forEach(output::write); offset += count
                }
                assertArrayEquals(cipher, output.toByteArray()); assertTrue(splitter.disabled); assertEquals(0L, budget.used)
            }
        }
    }

    @Test fun sharedBudgetExhaustionPreservesPendingPrefixAndReleasesOnlyItsReservation() {
        val budget = SplitterBudget(48)
        val first = MsgSplitter(TransportProtocol.INTERMEDIATE, budget)
        val second = MsgSplitter(TransportProtocol.INTERMEDIATE, budget)
        val prefix = hex("640000006161616161616161"); val other = hex("6400000062626262"); val following = ByteArray(8) { 'c'.code.toByte() }
        fun cipher(plain: ByteArray) = ByteArray(plain.size) { (plain[it].toInt() xor 0xa5).toByte() }
        assertTrue(first.split(cipher(prefix), prefix).isEmpty()); assertTrue(second.split(cipher(other), other).isEmpty()); assertEquals(40L, budget.used)
        val parts = first.split(cipher(following), following)
        assertEquals(listOf(12, 8), parts.map { it.size }); assertArrayEquals(cipher(prefix + following), parts.fold(ByteArray(0)) { all, part -> all + part })
        assertTrue(first.disabled); assertEquals(16L, budget.used)
        first.close(); second.close(); assertEquals(0L, budget.used)
    }

    @Test fun closeFlushAndLengthMismatchReleaseAllBufferedBytes() {
        val budget = SplitterBudget(4096)
        val splitter = MsgSplitter(TransportProtocol.INTERMEDIATE, budget)
        val prefix = hex("640000006161")
        splitter.split(prefix, prefix); assertEquals(12L, budget.used)
        assertArrayEquals(prefix, splitter.flush().single()); assertEquals(0L, budget.used)
        splitter.split(prefix, prefix)
        try { splitter.split(byteArrayOf(1), ByteArray(0)); fail() } catch (_: IllegalArgumentException) {}
        assertEquals(0L, budget.used); splitter.close(); assertEquals(0L, budget.used)
    }
}
